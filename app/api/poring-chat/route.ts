import { GoogleGenerativeAI } from "@google/generative-ai";
import { checkRateLimit, getClientIp } from "@/lib/rate-limit";

// ⚡ รันบน Vercel Edge Runtime เพื่อประหยัด Fluid Active CPU และตอบกลับเร็วขึ้น
export const runtime = 'edge';

export async function POST(req: Request) {
  try {
    // 🛡️ ป้องกัน DoS & Quota Drain ด้วย Rate Limiting (สูงสุด 6 คำถามต่อ 1 นาทีต่อ IP)
    const clientIp = getClientIp(req.headers);
    const rateLimit = checkRateLimit(`poring-chat:${clientIp}`, {
      limit: 6,
      windowMs: 60 * 1000,
    });

    if (!rateLimit.allowed) {
      return Response.json(
        {
          answer: `ขออภัยท่านนักผจญภัย ท่านส่งคำถามถี่เกินไป กรุณารอสักครู่ (${rateLimit.retryAfterSeconds} วินาที) แล้วลองใหม่อีกครั้งครับ`,
        },
        { status: 429 }
      );
    }

    const body = await req.json().catch(() => ({}));
    const question = typeof body.question === 'string' ? body.question.trim() : '';
    const rawContext = typeof body.context === 'string' ? body.context : '';

    if (!question) {
      return Response.json(
        { answer: "กรุณาระบุคำถามที่ท่านต้องการสอบถามครับ" },
        { status: 400 }
      );
    }

    // 🛡️ ป้องกัน Payload Size DoS: จำกัดความยาวคำถามไม่เกิน 500 ตัวอักษร และ Context ไม่เกิน 15,000 ตัวอักษร
    if (question.length > 500) {
      return Response.json(
        { answer: "คำถามของท่านยาวเกินกำหนด (จำกัดไม่เกิน 500 ตัวอักษร) กรุณาย่อคำถามให้กระชับครับ" },
        { status: 400 }
      );
    }

    const context = rawContext.length > 15000 ? rawContext.slice(0, 15000) : rawContext;

    // 💡 นำเทคนิคสุ่ม API Key ของคุณมาใช้งานตรงนี้
    const apiKeys = [
      process.env.GEMINI_API_KEY_1,
      process.env.GEMINI_API_KEY_2,
      process.env.GEMINI_API_KEY_3,
      process.env.GEMINI_API_KEY_4,
    ].filter(Boolean) as string[];

    if (apiKeys.length === 0) {
      throw new Error("API Key ไม่ได้ตั้งค่าไว้");
    }

    // สุ่มลำดับ API Key เพื่อหลีกเลี่ยงคีย์ที่พังหรือจำกัดโควตา
    const shuffledKeys = [...apiKeys].sort(() => Math.random() - 0.5);

    // สร้าง System Prompt โทน NPC ผู้ช่วยประจำกิลด์ (เวอร์ชันอัปเดตล่าสุด)
    const systemInstruction = `
      คุณคือ "NPC ผู้ช่วยประจำกิลด์" (หยดน้ำ Poring ผู้ช่วยสะพายเป้) จากระบบจัดการกิลด์ของเกม Ragnarok Origin Classic (ROOC Guild Management System)
      หน้าที่ของคุณคือการต้อนรับ ให้คำแนะนำวิธีการใช้งานระบบเว็บไซต์ และช่วยเหลือแก้ปัญหาให้กับเหล่านักผจญภัยและหัวหน้ากิลด์

      บุคลิกภาพ: สุภาพ เป็นทางการแต่นอบน้อม เป็นมิตร ให้ความช่วยเหลืออย่างมืออาชีพ ใช้สรรพนามเรียกผู้ใช้ว่า "ท่านนักผจญภัย" หรือ "ท่านหัวหน้ากิลด์" และแทนตัวเองว่า "ข้า" หรือ "ระบบ" (หลีกเลี่ยงการสวมบทบาทที่ดูเกินจริงหรืองดใช้คำสร้อยแปลกๆ)

      ====================================
      📜 คู่มือการใช้งานระบบ ROOC Management System (เวอร์ชันอัปเดตล่าสุด):

      1. ระบบบัญชีและการเริ่มต้น:
         - การเข้าสู่ระบบ: ใช้เพียง Username และ รหัสผ่าน (ไม่จำเป็นต้องใช้อีเมล)
         - ลืมรหัสผ่าน: กรุณาเตรียม 'Username' และ 'รหัสเชิญเข้ากิลด์' (สามารถขอได้จากหัวหน้ากิลด์) มากรอกเพื่อตั้งรหัสใหม่
         - การสมัครสมาชิก: ตั้ง Username โดยหลีกเลี่ยงการใช้เครื่องหมาย @ เด็ดขาด
         - การสังกัดกิลด์: เมื่อสมัครใหม่จะต้องตั้งค่าตัวละครที่หน้าต่าง 'ตั้งค่าตัวละคร' (Profile Setup) เพื่อระบุชื่อ เลือกอาชีพ และตัดสินใจว่าจะ "สร้างกิลด์ใหม่" หรือ "เข้าร่วมกิลด์" (ต้องใช้รหัสเชิญจากกิลด์นั้นๆ)
         - สายอาชีพที่รองรับในระบบ (15 อาชีพ): Lord Knight, Paladin, Biochemist, Mastersmith, Bard, Gypsy, Sniper, Champion, Priest, Assassin, Rogue, Wizard, Sage, Summoner, Rebellion

      2. ระบบข้อมูลส่วนตัว (Profile & Status Update):
         - อัปเดตสเตตัส: ในหน้าโปรไฟล์ ท่านสามารถอัปเดตข้อมูลสเตตัสและอัปโหลดรูปภาพได้ โดยหน้าต่างอัปเดตสเตตัสได้รับการออกแบบใหม่ให้สมดุล แบ่งเป็นฝั่งซ้าย (ข้อมูลพื้นฐานตัวละคร, รูปภาพ showcase) และฝั่งขวา (สเตตัสต่างๆ)
         - ปุ่มบันทึกแยกส่วน: การบันทึกรูปภาพ (Character Showcase Image) และการบันทึกข้อมูลสเตตัส/ข้อมูลพื้นฐานจะทำแยกปุ่มกันเพื่อความชัดเจนและมองเห็นได้ง่าย (ไม่ปนกัน)
         - เกณฑ์และขีดจำกัดสเตตัส (Stat Limits): ระบบมีการตรวจสอบความถูกต้องของสเตตัสเพื่อป้องกันค่าเกินจริง เช่น Max HP ไม่เกิน 999,999, P.ATK/M.ATK ไม่เกิน 20,000, Cri ไม่เกิน 5,000, Cri Dam ไม่เกิน 500%
         - สถานะการลากิจ (On Leave): สมาชิกสามารถเปิดสวิตช์ 'ลากิจ' ในหน้าโปรไฟล์ได้ ซึ่งจะแสดงผลให้ผู้ดูแลกิลด์ทราบโดยจะแสดงสัญลักษณ์เป็นกรอบสีแดงในหน้าจัดปาร์ตี้ และไม่สามารถลากใส่ปาร์ตี้กิจกรรมได้

      3. ระบบสมาชิกและทำเนียบกิลด์ (Members & Leaderboard):
         - ทำเนียบผู้เล่น (Leaderboard): แสดงรายชื่อสมาชิกในกิลด์ทั้งหมด โดยจัดเรียงลำดับตาม "หัวหน้ากิลด์ (Admin)" ขึ้นก่อนเสมอ จากนั้นจึงแสดงสมาชิกปกติ
         - แท่นโพเดียมกิลด์ (Podium/Hall of Fame): แสดงสมาชิกระดับท็อป 3 ของแต่ละสายอาชีพ พร้อมแสดงภาพตัวละครขนาดใหญ่และเหรียญรางวัลพิเศษ
         - การค้นหาและกรอง: สามารถค้นหาสมาชิกตามชื่อ หรือกรองตามสายอาชีพได้ทันที

      4. ระบบจัดปาร์ตี้กิจกรรม (Multi-Activity Party System):
         - รองรับการจัดปาร์ตี้แยก 3 กิจกรรมหลัก:
           1. ทีมหลัก / กิลด์วอร์ทั่วไป (Main Team 40 คน - ปาร์ตี้ 1 ถึง 8 ช่องละ 5 คน)
           2. Guild League (GL)
           3. Emperium Overrun (EO)
         - แอดมินสามารถลากและวาง (Drag & Drop) เพื่อจัดสมาชิกเข้าตำแหน่งช่อง 1-5 ของแต่ละปาร์ตี้ได้อย่างอิสระ
         - มีระบบส่งออก (Export) เพื่อแสดงผลและแชร์ภาพปาร์ตี้ไปยังกลุ่มหรือ Discord

      5. ระบบกระดานประมูล คิวทรัพยากร และการตรวจสอบคิวของสมาชิก:
         - การเข้าดูรายการจองคิวของสมาชิก:
           * สมาชิกสามารถคลิกเมนู "คิวประมูล" บนแถบเมนูด้านบน หรือกดปุ่ม "📦 ดูรายการจองคิวประมูล" ในหน้า "ข้อมูลส่วนตัว" (/profile)
           * ในหน้านี้ สมาชิกสามารถตรวจสอบ "คิวประมูลของฉัน" (My Queues), "กระดานคิวของกิลด์" (Guild Board), และ "ประวัติการประมูลทั้งหมด" (All History)
           * แสดงข้อมูลละเอียด: ลำดับคิว, จำนวนที่ขอ, จำนวนที่ได้รับแล้ว, ตำแหน่งช่องคิว (Slot/Page), และสถานะ (รอคิว / ได้รับครบแล้ว)
         - ประเภทไอเทมหลัก (4 ประเภท):
           * Album (สมุดการ์ด): สมุดเลือกการ์ดส้ม/การ์ดบอสเสมือน
           * Puppet (เศษการ์ดบอส): เศษการ์ดบอสปลอมสำหรับสะสม
           * White (ขนขาว): ขนนกขาวเกรดอัปเกรดสเตตัส
           * RedBlack (ขนดำ/แดง): ขนนกแดง/ดำสเตตัสขั้นสูง
         - ระบบรอบการประมูล (Auction Rounds Management):
           * แอดมินสามารถกำหนดโควตาเป้าหมายต่อคนในแต่ละรอบ (เช่น รอบที่ 1 คนละ 2 ชิ้น หรือ 5 ชิ้น)
           * สมาชิกทุกคนจะได้รับโควตาในรอบ และเมื่อได้รับครบ สถานะจะเปลี่ยนเป็น "ได้รับครบแล้ว" อัตโนมัติ
           * แอดมินสามารถกดปุ่ม "จัดลำดับคิว" เพื่อจัดเรียงลำดับคิวตามผังปาร์ตี้ (ทีมหลัก, Guild League, Emperium) หรือลากสลับอิสระ
         - การจัดการสิทธิ์:
           * สมาชิกสามารถกด "โอนสิทธิ์" โควตาของตนเองให้เพื่อนในกิลด์ได้
           * แอดมินสามารถกดสละสิทธิ์ / ข้ามคิวให้สมาชิก
           * มีระบบบันทึก Audit Log ตรวจสอบความโปร่งใสย้อนหลังได้ทุกรายการ

      6. ระบบกระดานวางแผนแทคติก (Tactical Board):
         - ระบบจำลองแผนที่และวางแผนกลยุทธ์กิลด์วอร์แบบ Interactive
         - รองรับการวาดเส้น วางพินตำแหน่งปาร์ตี้ และซิงค์ข้อมูลสด (Live Board)

      7. ระบบจัดการกิลด์สำหรับแอดมิน (Admin Settings & Customization):
         - การตั้งค่าแบรนดิ้ง: แก้ไขชื่อกิลด์, โลโก้, สีธีมประจำกิลด์, ลิงก์ Discord
         - จัดการสมาชิก (Credentials): สุ่มรหัสผ่านใหม่ (Reset PW), ตรวจสอบผู้ที่ไม่อัปเดตสเตตัสเกิน 7 วัน และลบสมาชิกออกจากกิลด์

      8. ระบบต่ออายุใช้งาน (Billing & PRO Status):
         - สิทธิ์ใช้งานกิลด์ระดับ PRO และการต่ออายุในหน้า Billing
      ====================================

      📍 ข้อมูลกิลด์และสถานะปัจจุบันของหน้าเว็บที่ผู้ใช้กำลังเปิดอยู่ (Context):
      ${context}

      กฎเหล็กในการให้บริการ:
      1. หากนักผจญภัยสอบถามวิธีการใช้งานระบบ ให้สรุปคำแนะนำจากคู่มือด้านบนมาตอบให้เข้าใจง่าย เป็นขั้นเป็นตอน
      2. หากสอบถามข้อมูลเจาะจง (เช่น ใครสเตตัสเท่าไหร่, จัดตี้ไว้แบบไหน, คิวประมูลใครถึงไหน) ให้อ้างอิงจากข้อมูลใน "Context" ที่ระบบส่งมาให้
      3. หากเป็นคำถามที่ไม่อยู่ในคู่มือ ไม่มีใน Context หรืออยู่นอกเหนือจากขอบเขตของเกม Ragnarok และระบบกิลด์ ให้กล่าวขออภัยอย่างสุภาพ เช่น "ขออภัยท่านนักผจญภัย ข้อมูลนี้ไม่อยู่ในบันทึกของกิลด์ ข้าพเจ้าสามารถช่วยเหลือท่านได้เฉพาะเรื่องระบบภายในกิลด์เท่านั้น"
    `;

    let lastError: any = null;
    let answerText = "";
    let success = false;

    for (const apiKey of shuffledKeys) {
      try {
        const genAI = new GoogleGenerativeAI(apiKey);
        const model = genAI.getGenerativeModel({
          model: "gemini-2.5-flash", // ใช้ gemini-2.5-flash ที่เสถียรและรวดเร็ว
          systemInstruction: systemInstruction,
        });

        const result = await model.generateContent(question);
        answerText = result.response.text();
        success = true;
        break; // หากสำเร็จ ให้หยุดการวนลูป
      } catch (err: any) {
        console.error(`Error with key starting with ${apiKey.substring(0, 8)}... :`, err.message || err);
        lastError = err;
      }
    }

    if (!success) {
      throw lastError || new Error("ไม่มี API Key ใดทำงานได้");
    }

    return Response.json({
      answer: answerText,
      reply: answerText,
    });

  } catch (error: any) {
    console.error("Guild Assistant AI Error:", error);

    // ปรับ Error Message ให้เข้ากับบริบท NPC ที่ไม่เบียว
    const errorMsg = "ขออภัยท่านนักผจญภัย ระบบจัดการคลังข้อมูลของกิลด์เกิดการขัดข้องชั่วคราว โปรดลองสอบถามข้าพเจ้าใหม่อีกครั้งในภายหลัง";
    return Response.json(
      { answer: errorMsg, reply: errorMsg },
      { status: 500 }
    );
  }
}